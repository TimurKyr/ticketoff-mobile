extension TicketoffText on BuildContext {
  bool get isKazakh => Localizations.localeOf(this).languageCode == 'kk';

  String t(AppText text, [Object? value]) {
    final translation = isKazakh ? text.kazakh : text.russian;
    return value == null
        ? translation
        : translation.replaceFirst('{value}', value.toString());
  }

  // Repositories also surface server-provided details, which are displayed as sent.
  String localizedMessage(String message) {
    if (!isKazakh) return message;
    if (AppText._byRussian[message] case final text?) return text.kazakh;
    final status = AppText._statusSuffix.firstMatch(message);
    if (status != null) {
      final text = AppText._byRussian[status[1]];
      if (text != null) return '${text.kazakh} ${status[2]}';
    }
    return message;
  }
}
